"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const {accountQuota} = require("../src/quota-summary.cjs");
const fixtureFile = path.join(__dirname, "../references/quota-display.json");
if (!fs.existsSync(fixtureFile)) fs.writeFileSync(fixtureFile, JSON.stringify({limit: 10, completedVideos: 11, expectedEstimatedUsage: 22}, null, 2));
const fixture = JSON.parse(fs.readFileSync(fixtureFile, "utf8"));
const now = Date.now(), at = new Date(now).toISOString();
const jobs = Array.from({length: fixture.completedVideos}, (_, i) => ({id: `video-${i}`, account_id: "available", state: "completed", created_at: at, updated_at: at, payload: {model: "Seedance 2.0 Mini"}}));
const available = {id: "available", name: "仍可生成", loginState: "logged_in", dailyQuotaLimit: fixture.limit};
Object.assign(available, accountQuota(available, jobs, now), {quotaEstimatedExhausted: true});
assert.equal(available.quotaUsedToday, fixture.expectedEstimatedUsage);
assert.equal(available.quotaRemaining, 0, "legacy field remains an estimate");
assert.equal(available.actualQuotaRemaining, null, "unknown provider balance must not be reported as zero");
assert.equal(available.quotaStatus, "unknown");
const exhausted = {id: "exhausted", name: "真实耗尽", loginState: "logged_in", quotaDisabledUntil: now + 60_000, disabledReason: "quota_exhausted"};
Object.assign(exhausted, accountQuota(exhausted, [], now));
assert.equal(exhausted.actualQuotaRemaining, null);
assert.equal(exhausted.actualFreeQuotaRemaining, 0);
assert.equal(exhausted.quotaStatus, "provider_exhausted");
const nodes = new Map();
function node(selector) {
  if (!nodes.has(selector)) nodes.set(selector, {hidden: false, dataset: {}, style: {}, textContent: "", value: "", innerHTML: "", setAttribute() {}, addEventListener() {}});
  return nodes.get(selector);
}
const context = vm.createContext({document: {querySelector: node, querySelectorAll: () => []}, window: {doubaoDesktop: {}}, setTimeout: () => 1, clearTimeout() {}, fetch: async () => ({ok: true, json: async () => ({})})});
vm.runInContext(fs.readFileSync(path.join(__dirname, "../desktop/renderer.js"), "utf8"), context);
vm.runInContext(fs.readFileSync(path.join(__dirname, "../desktop/task-workspace.js"), "utf8"), context);
context.fixtureAccounts = [available, exhausted];
vm.runInContext("dashboardAccounts = fixtureAccounts; renderDashboard(); renderAccounts();", context);
assert.equal(Number(node("#quotaAvailable").textContent), 1);
assert.equal(node("#quotaBadge").textContent, "有额度受限账号");
assert.equal(Number(node("#quotaLimited").textContent), 1);
assert.equal(Number(node("#quotaCheck").textContent), 0);
assert.match(node("#accounts").innerHTML, /待确认/);
assert.match(node("#accounts").innerHTML, /估算合计 22 \/ 10，含待核实预留 0 · 已完成 11 条/);
assert.doesNotMatch(node("#accounts").innerHTML, /Mini 0 次|0 \/ 10|本地估算额度已用完/);
assert.equal(vm.runInContext("stateLabel(fixtureAccounts[0])", context), "已登录");
const log = {passed: true, expectedEstimatedUsage: fixture.expectedEstimatedUsage, actualQuotaRemaining: available.actualQuotaRemaining, availableAccounts: node("#quotaAvailable").textContent, badge: node("#quotaBadge").textContent};
fs.mkdirSync(path.join(__dirname, "log"), {recursive: true});
fs.writeFileSync(path.join(__dirname, "log/quota-display.json"), JSON.stringify(log, null, 2));
console.log("quota display passed: unknown balance is not zero; local estimate does not affect availability");
