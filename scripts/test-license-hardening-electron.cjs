"use strict";
const {app,BrowserWindow}=require("electron");
const fs=require("node:fs"),os=require("node:os"),path=require("node:path"),http=require("node:http"),assert=require("node:assert/strict");
const {EmbeddedBrowserManager}=require("../src/embedded-browser-manager.cjs");
const root=fs.mkdtempSync(path.join(os.tmpdir(),"license-hardening-ui-"));
app.setPath("userData",root);app.disableHardwareAcceleration();app.commandLine.appendSwitch("no-sandbox");
let ui,main,manager,host;
app.whenReady().then(async()=>{
  const preload=path.join(root,"preload.cjs");
  fs.writeFileSync(preload,`
    window.fixtureStatus={valid:true,permanent:true};window.secretReads=0;
    window.doubaoDesktop={licenseStatus:async()=>window.fixtureStatus,licenseSecret:async()=>{window.secretReads++;if(window.delaySecret)return new Promise(r=>window.resolveSecret=r);return 'FAKE-TEST-KEY';},showLicense:async()=>{}};
    window.fetch=async()=>({ok:true,json:async()=>({accounts:[],jobs:[]})});
    window.setInterval=(fn,ms)=>{if(ms===5000)window.fixtureTick=fn;return 1;};
  `);
  ui=new BrowserWindow({show:false,width:1200,height:900,webPreferences:{preload,sandbox:false,contextIsolation:false,nodeIntegration:false,backgroundThrottling:false}});
  await ui.loadFile(path.join(__dirname,"../desktop/index.html"));
  const page=ui.webContents;
  const run=code=>page.executeJavaScript(`(async()=>{${code};await new Promise(r=>setTimeout(r,40));})()`);
  const inspect=()=>page.executeJavaScript(`({reads:window.secretReads,workbench:!document.querySelector('.app-shell').hidden,candidate:document.querySelector('#licenseSecret').value,stored:document.querySelector('#storedLicenseSecret')?.value,fieldType:document.querySelector('#storedLicenseSecret')?.type,dialog:document.querySelector('#licenseDialog').open})`);
  await run("");
  assert.equal((await inspect()).reads,0,"startup must not decrypt stored key");
  await run("document.querySelector('#openLicense').click()");
  assert.equal((await inspect()).reads,0,"opening dialog must not decrypt");
  await run("document.querySelector('#licenseSecret').value='candidate-being-edited';window.fixtureTick()");
  assert.equal((await inspect()).candidate,'candidate-being-edited');
  await run("document.querySelector('#revealLicense').click()");
  assert.equal((await inspect()).stored,'FAKE-TEST-KEY');
  assert.equal((await inspect()).candidate,'candidate-being-edited');
  await run("window.fixtureStatus={valid:false,code:'DOUBAO_LICENSE_EXPIRED'};window.fixtureTick()");
  let view=await inspect();assert.equal(view.workbench,false);assert.notEqual(view.stored,'FAKE-TEST-KEY');assert.equal(view.candidate,'candidate-being-edited');
  await run("window.fixtureStatus={valid:true,permanent:true};window.fixtureTick()");
  await run("document.querySelector('#openLicense').click();window.delaySecret=true");
  await run("document.querySelector('#revealLicense').click();document.querySelector('#closeLicense').click()");
  await run("window.resolveSecret('FAKE-LATE-KEY')");
  view=await inspect();assert.notEqual(view.stored,'FAKE-LATE-KEY');assert.equal(view.fieldType,'password');assert.equal(view.candidate,'');
  await run("window.delaySecret=false;document.querySelector('#openLicense').click()");
  await run("document.querySelector('#revealLicense').click()");
  assert.equal((await inspect()).stored,'FAKE-TEST-KEY');
  await run("document.querySelector('#closeLicense').click()");
  assert.notEqual((await inspect()).stored,'FAKE-TEST-KEY');
  console.log("UI passed: continuous polling while editing, expiry hides key, explicit reveal, separate candidate, close/late-response privacy");

  host=http.createServer((_req,res)=>{res.setHeader('Content-Type','text/html');res.end('<button id="send" onclick="window.sent=(window.sent||0)+1">确认生成</button><textarea></textarea>');});
  await new Promise(r=>host.listen(0,'127.0.0.1',r));const base=`http://127.0.0.1:${host.address().port}`;
  main=new BrowserWindow({show:false});manager=new EmbeddedBrowserManager({mainWindow:main});manager.platformUrl=()=>base+'/chat/';manager.taskUrl=(_a,id)=>base+'/chat/'+id;
  const account={id:'manual-fixture'},job={id:'job-fixture',account,taskContext:{conversationId:'123456789'}};
  const running=await manager.automationSession({id:'running-fixture'}),release=manager.retainAutomation({id:'running-fixture'});
  await manager.takeoverTask(job);const manual=manager.automationSessions.get(account.id);
  await manager.openTask(job);const taskView=manager.taskViews.get(job.id);
  await manager.open({id:'ordinary-fixture'});const ordinary=manager.sessions.get('ordinary-fixture');
  await manual.webContents.executeJavaScript("document.querySelector('#send').click()");
  assert.equal(await manual.webContents.executeJavaScript('window.sent'),1);
  await manager.setLicenseValid(false);
  assert.equal(manual.window.isVisible(),false);assert.equal(manual.webContents.isDestroyed(),false);
  assert.equal(running.webContents.isDestroyed(),false);assert.equal(manager.automationUsers.get('running-fixture'),1);
  assert.equal(taskView.webContents.isDestroyed(),true);assert.equal(ordinary.webContents.isDestroyed(),true);
  assert.equal(manager.manualOwners.get(account.id),job.id);
  await manual.webContents.executeJavaScript("document.querySelector('#send').click()");assert.equal(await manual.webContents.executeJavaScript('window.sent'),1);
  manual.window.show();assert.equal(manual.window.isVisible(),false,"blocked page cannot resurface");
  for (const action of [()=>manager.open(account),()=>manager.openTask(job),()=>manager.takeoverTask(job)]) await assert.rejects(action,{code:'DOUBAO_LICENSE_REQUIRED'});
  assert.throws(()=>manager.showActive(),{code:'DOUBAO_LICENSE_REQUIRED'});
  await manager.setLicenseValid(true);assert.equal(manual.window.isVisible(),false);
  await manual.webContents.executeJavaScript("document.querySelector('#send').click()");assert.equal(await manual.webContents.executeJavaScript('window.sent'),1,'recovery does not silently re-enable manual input');
  await manager.takeoverTask(job);await manual.webContents.executeJavaScript("document.querySelector('#send').click()");assert.equal(await manual.webContents.executeJavaScript('window.sent'),2);
  await manager.freezeTakeover(job);release();
  const realReadOnly=manager.setTaskReadOnly.bind(manager);
  let enter,finish;
  const entered=new Promise(r=>enter=r),held=new Promise(r=>finish=r);
  manager.setTaskReadOnly=async(item,readOnly)=>{if(!readOnly){enter();await held;}return realReadOnly(item,readOnly);};
  const opening=manager.takeoverTask(job);
  const rejection=assert.rejects(opening,{code:'DOUBAO_LICENSE_REQUIRED'});
  await entered;await manager.setLicenseValid(false);finish();await rejection;
  assert.equal(manual.taskReadOnly,true);assert.equal(manual.window.isVisible(),false);
  manager.setTaskReadOnly=realReadOnly;await manager.setLicenseValid(true);
  await manual.webContents.executeJavaScript("document.querySelector('#send').click()");assert.equal(await manual.webContents.executeJavaScript('window.sent'),2,'takeover race must stay frozen after recovery');
  await manager.freezeTakeover(job);
  console.log(`Window enforcement passed: manual freeze, retained generation/session/lock, task-view closure, blocked open, explicit recovery; Electron ${process.versions.electron}`);
}).catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{manager?.dispose();main?.destroy();ui?.destroy();host?.close();app.exit(process.exitCode||0);});
