"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const fixture = require("../references/timeout-recovery-fixture.json");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "doubao-timeout-test-"));
const dataRoot = path.join(root, "data");
const accountsFile = path.join(root, "accounts.json");
fs.mkdirSync(dataRoot, {recursive: true});
fs.writeFileSync(accountsFile, JSON.stringify({accounts: [{id: fixture.accountId, name: "测试账号", loginState: "logged_in"}]}));
process.env.DOUBAO_DATA_ROOT = dataRoot;
process.env.DOUBAO_TEMP_ROOT = path.join(dataRoot, "temp");
process.env.DOUBAO_PROFILE_ROOT = path.join(dataRoot, "profiles");
process.env.DOUBAO_ACCOUNTS_FILE = accountsFile;
process.env.DOUBAO_RESULT_RECOVERY_DELAY_MS = String(fixture.recoveryDelayMs);
process.env.DOUBAO_TEST_MODE = "1";
const {TaskStore} = require("../src/task-store.cjs");
const {queueResultRecovery, isResultWaitTimeout} = require("../src/server.cjs");
const store = new TaskStore(path.join(dataRoot, "jobs.json"));
const job = store.create(fixture.jobId, {prompt: "测试", timeoutMs: 1000, imageAssets: []});
const timeout = Object.assign(new Error("等待当前任务视频资源超时"), {code: "DOUBAO_VIDEO_RESULT_TIMEOUT", submittedVerified: true, conversationId: fixture.conversationId});
assert.equal(isResultWaitTimeout(timeout), true);
assert.equal(queueResultRecovery(job, {id: fixture.accountId}, timeout), true);
const queued = store.get(fixture.jobId);
assert.equal(queued.state, "queued");
assert.equal(queued.payload.resumeExisting, true);
assert.equal(queued.payload.accountLockRequired, true);
assert.equal(queued.payload.conversationId, fixture.conversationId);
assert.equal(queued.payload.resultRecoveryAttempts, 1);
assert.equal(store.get(fixture.jobId).state, "queued");
console.log("timeout recovery ok (same conversation queued without resubmission)");
store.close();
fs.rmSync(root, {recursive: true, force: true});
