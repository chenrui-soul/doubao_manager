"use strict";
const assert = require("node:assert/strict");
const vm = require("node:vm");
const {BrowserController,classifyDoubaoFailureMessage,isPaidQuotaConfirmation} = require("../src/vendor/browser-controller.cjs");
const controller = Object.create(BrowserController.prototype);
const user = {className:"justify-end", innerText:"测试视频 时间轴 连续性硬约束 禁止项", getBoundingClientRect:()=>({width:100,height:30}), getAttribute:()=>null, querySelector:()=>null};
const reply = text => ({...user,className:"assistant", innerText:text});
let messages = [user, reply("视频生成参数确认，确认后我再开始生成"), {...user,innerText:"不需要，直接帮我生成视频。"}, reply("视频生成中")];
const root = {get innerText(){return messages.map(m=>m.innerText).join(' ');}, querySelectorAll:()=>messages};
const context = {location:{pathname:"/chat/123456789"}, getComputedStyle:()=>({display:"block",visibility:"visible",position:"static"}), document:{body:root, querySelector:()=>root, querySelectorAll:s=>s==='[data-message-id]'?messages:[]}};
controller.evaluate=async (_session, expression)=>vm.runInNewContext(expression, context);
(async()=>{
  const generated = await controller.readSubmissionState({}, "测试视频");
  assert.equal(generated.scopedGenerating,true,"old confirmation and user prompt must not mask generation");
  assert.equal(generated.planningConfirmation,false);
  messages = [user,reply("视频生成参数确认，确认后我再开始生成")];
  const pending = await controller.readSubmissionState({}, "测试视频");
  assert.equal(pending.planningConfirmation,true);
  assert.equal(pending.scopedGenerating,false);
  const cardReply=reply("生成视频 时间轴 连续性硬约束 禁止项 你的视频生成好了。");
  cardReply.querySelector=selector=>selector.includes('block-video')?{}:null;
  messages=[user,cardReply];
  const card=await controller.readSubmissionState({},"测试视频");
  assert.equal(card.videoTaskCard,true,"real result card exists before a video element is mounted");
  assert.equal(card.planningConfirmation,false,"card prompt text is not a confirmation request");
  const paid="今日视频生成免费额度已用完，本次将消耗付费额度，并使用优先生成通道。预计等待5分钟。";
  assert.equal(classifyDoubaoFailureMessage(paid).failed,false);
  assert.equal(isPaidQuotaConfirmation("今日视频生成免费额度已用完，本次将消耗付费额度。是否继续生成？确认生成"), true);
  assert.equal(classifyDoubaoFailureMessage("今日视频生成免费次数用完").quotaExhausted,true);
  messages=[user,reply("视频生成参数确认，确认后我再开始生成"),reply(paid),reply("你的视频生成好了。")];
  const completed=await controller.readSubmissionState({},"测试视频");
  assert.equal(completed.providerTerminal,false);
  assert.equal(completed.scopedGenerating,true);
  let restoreChecks=0;
  controller.evaluate=async(_session,expression)=>expression==='location.href'?'https://www.doubao.com/chat/123456789':({conversationId:'123456789',restored:++restoreChecks>=2});
  const restored=await controller.restoreConversation({}, {payload:{conversationId:'123456789',prompt:'测试视频'}});
  assert.equal(restored.restored,true);
  assert.equal(restoreChecks,2,'SPA messages can arrive after navigation completes');
  const {AccountScheduler}=require('../src/account-scheduler.cjs');
  const scheduler=new AccountScheduler([{id:'account-006',loginState:'logged_in',quotaDisabledUntil:Date.now()+60000}]);
  assert.equal(scheduler.available().length,0);
  const monitoring=await scheduler.acquire(100,'account-006',[],{monitorExisting:true});
  assert.equal(monitoring.id,'account-006');
  assert.equal(scheduler.busy.has('account-006'),true);
  scheduler.release(monitoring);
  assert.equal(scheduler.available().length,0,'monitoring must not unlock quota for new submissions');
  controller.connect=async()=>({send:async()=>({exceptionDetails:{exception:{description:"ReferenceError: missing helper"}}})});
  await assert.rejects(BrowserController.prototype.evaluate.call(controller,{embedded:true},"missing()"),{code:"DOUBAO_PAGE_EVALUATION_FAILED"});
  console.log("submission page runtime ok: isolated JS, latest assistant confirmation, surfaced exceptions");
})().catch(e=>{console.error(e);process.exitCode=1;});
