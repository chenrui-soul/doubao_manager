"use strict";
const {app,BrowserWindow}=require("electron"),assert=require("node:assert/strict");
const {probePageBlocker}=require("../src/vendor/page-blockers.cjs");
const {BrowserController,classifySubmissionEvidence}=require("../src/vendor/browser-controller.cjs");
const {probeConversationTurn}=require("../src/vendor/composer-guard.cjs");
app.disableHardwareAcceleration();app.commandLine.appendSwitch("no-sandbox");
let win;
app.whenReady().then(async()=>{
 win=new BrowserWindow({show:false,width:1000,height:800,webPreferences:{backgroundThrottling:false}});
 const wc=win.webContents,c=Object.create(BrowserController.prototype);
 c.evaluate=async(_s,e)=>wc.executeJavaScript(e);
 wc.debugger.attach("1.3");c.connect=async()=>({send:(m,p)=>wc.debugger.sendCommand(m,p)});
 const load=html=>wc.loadURL("data:text/html;charset=utf-8,"+encodeURIComponent(html));
 await load('<textarea style="position:absolute;top:500px;width:700px;height:100px"></textarea><div role="dialog" style="position:fixed;inset:100px;background:white">安全确认：素材均已获充分授权<button onclick="window.accepted=true">确认</button></div>');
 assert.equal((await c.evaluate({},`(${probePageBlocker.toString()})()`)).kind,"asset_authorization");
 await assert.rejects(()=>c.fillComposer({phase:"submitting"},"确认生成"),e=>e.code==="DOUBAO_ASSET_AUTHORIZATION_REQUIRED"&&e.notSentVerified===false);
 assert.equal(await wc.executeJavaScript('Boolean(window.accepted)'),false);
 assert.equal(await wc.executeJavaScript('document.querySelector("textarea").value'),"");
 await load('<div role="dialog" style="position:fixed;inset:100px;background:white">下载电脑版使用完整功能<button onclick="this.parentElement.remove()">下次提醒我</button></div>');
 await c.checkPageBlocker({}, {dismissPromotion:true});
 assert.equal((await c.evaluate({},`(${probePageBlocker.toString()})()`)).kind,"");
 await load('<article data-message-id="old">安全确认：素材均已获充分授权，确认</article><textarea style="position:absolute;top:500px;width:700px;height:100px"></textarea>');
 assert.equal((await c.evaluate({},`(${probePageBlocker.toString()})()`)).kind,"");
 assert.equal(await c.fillComposer({},"普通确认",{timeoutMs:1500,stableMs:20}),true);
 await load('<div style="position:absolute;top:400px"><div data-message-id="new-confirmation" data-role="user">普通确认</div></div><textarea style="position:absolute;top:500px;width:700px;height:100px"></textarea>');
 const delivered=await c.evaluate({},`(${probeConversationTurn.toString()})("普通确认")`);
 assert.equal(delivered.delivered,true);assert.equal(delivered.queued,false,"a delivered message wrapper near the composer is not a queued chip");
 assert.equal(classifySubmissionEvidence({after:{conversationId:"12345678",scopedGenerating:true,paidQuotaPrompt:true}}).confirmed,false);
 assert.equal(classifySubmissionEvidence({after:{conversationId:"12345678",scopedGenerating:true,providerTerminal:true}}).confirmed,false);
 console.log("Stage A real Chromium: authorization blocks input without accepting, promotion dismissal, prose not a modal, composer input, quota/confirmation not generation passed");
}).catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{win?.destroy();app.exit(process.exitCode||0);});
